package osreinstall

import (
	"archive/tar"
	"bufio"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/json"
	"errors"
	"io"
	"path"
	"strings"

	"github.com/petauron/vastora/internal/secret"
	"golang.org/x/crypto/ssh"
)

func validPublicKeys(input []byte) bool {
	return validAuthorizedKeys(input, true)
}

func validAuthorizedKeys(input []byte, requireKey bool) bool {
	if len(input) > 64<<10 || (requireKey && len(input) == 0) {
		return false
	}
	scanner := bufio.NewScanner(bytes.NewReader(input))
	count := 0
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, _, options, rest, err := ssh.ParseAuthorizedKey([]byte(line))
		if err != nil || len(options) != 0 || len(bytes.TrimSpace(rest)) != 0 {
			return false
		}
		switch key.Type() {
		case ssh.KeyAlgoED25519, ssh.KeyAlgoRSA, ssh.KeyAlgoECDSA256, ssh.KeyAlgoECDSA384, ssh.KeyAlgoECDSA521:
		default:
			return false
		}
		count++
	}
	return scanner.Err() == nil && (!requireKey || count > 0) && count <= 32
}

// AccessSnapshot contains protected host access material. It is only sent to
// Center encrypted under the per-operation recovery password.
type AccessSnapshot struct {
	Username       string `json:"username"`
	SSHPort        int    `json:"sshPort"`
	SudoPolicy     string `json:"sudoPolicy"`
	SSHArchive     []byte `json:"sshArchive"`
	AuthorizedKeys []byte `json:"authorizedKeys"`
	RootKeys       []byte `json:"rootKeys,omitempty"`
	AgentUnit      []byte `json:"agentUnit"`
}

func ValidateAccessSnapshot(a AccessSnapshot, expectedUser string, expectedPort int, expectedHostKey string) error {
	bad := func() error { return errors.New("reinstall: unsupported or unsafe access snapshot") }
	if a.Username != expectedUser || !safeUser.MatchString(a.Username) || a.SSHPort != expectedPort || a.SSHPort < 1 || a.SSHPort > 65535 ||
		(a.SudoPolicy != "none" && a.SudoPolicy != "passwordless_all") || (a.Username == "root" && a.SudoPolicy != "none") ||
		(a.Username != "root" && a.SudoPolicy != "passwordless_all") || !validPublicKeys(a.AuthorizedKeys) ||
		!validAuthorizedKeys(a.RootKeys, false) || len(a.AgentUnit) == 0 || len(a.AgentUnit) > 16<<10 || len(a.SSHArchive) == 0 || len(a.SSHArchive) > 512<<10 {
		return bad()
	}
	compressed, err := gzip.NewReader(bytes.NewReader(a.SSHArchive))
	if err != nil {
		return bad()
	}
	unpacked, err := io.ReadAll(io.LimitReader(compressed, (3<<20)+1))
	closeErr := compressed.Close()
	if err != nil || closeErr != nil || len(unpacked) > 3<<20 {
		return bad()
	}
	r := tar.NewReader(bytes.NewReader(unpacked))
	names := map[string]bool{}
	var private, public []byte
	for count := 0; ; count++ {
		h, err := r.Next()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil || count >= 128 {
			return bad()
		}
		name := strings.TrimSuffix(h.Name, "/")
		if name == "" || path.Clean(name) != name || !strings.HasPrefix(name, "etc/ssh/") || strings.HasPrefix(name, "etc/ssh/ssh_config.d/20-systemd-ssh-proxy.conf/") || names[name] || h.Uid != 0 || h.Gid != 0 || h.Size < 0 || h.Size > 1<<20 {
			return bad()
		}
		if h.Typeflag == tar.TypeSymlink {
			if name != "etc/ssh/ssh_config.d/20-systemd-ssh-proxy.conf" || h.Linkname != "/usr/lib/systemd/ssh_config.d/20-systemd-ssh-proxy.conf" || h.Size != 0 {
				return bad()
			}
		} else if h.Mode&0022 != 0 || (h.Typeflag != tar.TypeDir && h.Typeflag != tar.TypeReg) {
			return bad()
		}
		names[name] = true
		body, err := io.ReadAll(io.LimitReader(r, h.Size+1))
		if err != nil || int64(len(body)) != h.Size {
			return bad()
		}
		if name == "etc/ssh/ssh_host_ed25519_key" {
			if h.Mode&0077 != 0 {
				return bad()
			}
			private = body
		}
		if name == "etc/ssh/ssh_host_ed25519_key.pub" {
			public = body
		}
	}
	signer, err := ssh.ParsePrivateKey(private)
	if err != nil {
		return bad()
	}
	key, _, _, rest, err := ssh.ParseAuthorizedKey(public)
	if err != nil || len(bytes.TrimSpace(rest)) != 0 || key.Type() != ssh.KeyAlgoED25519 || !bytes.Equal(key.Marshal(), signer.PublicKey().Marshal()) || ssh.FingerprintSHA256(key) != expectedHostKey {
		return bad()
	}
	if !names["etc/ssh/sshd_config"] {
		return bad()
	}
	return nil
}

// SealAccessSnapshot consumes the per-operation 32-byte crypto/rand token
// generated by Center, encoded as base64url. It is not a human password;
// SHA-256 maps that 256-bit random secret to an AES key without reducing its
// entropy. Keep this derivation stable for retained recovery snapshots.
func SealAccessSnapshot(a AccessSnapshot, password, taskID string) ([]byte, error) {
	if len(password) < 32 || !safeAgentID.MatchString(taskID) {
		return nil, errors.New("reinstall: invalid access protection")
	}
	raw, err := json.Marshal(a)
	if err != nil {
		return nil, err
	}
	key := sha256.Sum256([]byte(password))
	return secret.Seal(key[:], raw, []byte("os-reinstall-access:"+taskID))
}
func OpenAccessSnapshot(sealed []byte, password, taskID string) (AccessSnapshot, error) {
	var a AccessSnapshot
	if len(sealed) == 0 || len(sealed) > 800<<10 || len(password) < 32 || !safeAgentID.MatchString(taskID) {
		return a, errors.New("reinstall: invalid protected access")
	}
	key := sha256.Sum256([]byte(password))
	raw, err := secret.Open(key[:], sealed, []byte("os-reinstall-access:"+taskID))
	if err != nil || json.Unmarshal(raw, &a) != nil {
		return AccessSnapshot{}, errors.New("reinstall: cannot open protected access")
	}
	return a, nil
}
